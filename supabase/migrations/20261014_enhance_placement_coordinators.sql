-- 7F: Create College With Multiple Initial Placement Coordinators
-- Documented rule: colleges.tpo is set to the name of the FIRST coordinator in p_coordinators array for backward compatibility
CREATE OR REPLACE FUNCTION create_college_with_coordinators(
    p_college JSONB,
    p_coordinators JSONB DEFAULT '[]'::JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_u RECORD;
    v_college RECORD;
    v_college_name TEXT;
    v_primary_tpo TEXT := NULL;
    v_coord_item JSONB;
    v_coord RECORD;
    v_coord_name TEXT;
    v_created_coords JSONB := '[]'::JSONB;
BEGIN
    SELECT * INTO v_u FROM get_saarthi_auth_user();
    IF v_u.user_id IS NULL AND current_user NOT IN ('postgres', 'service_role', 'supabase_admin') THEN
        RAISE EXCEPTION 'Authentication required: caller must be an authenticated user';
    END IF;

    IF v_u.user_role NOT IN ('admin', 'recruiter') THEN
        RAISE EXCEPTION 'Unauthorized: only recruiters and admins can create colleges and placement coordinators';
    END IF;

    v_college_name := trim(p_college->>'name');
    IF v_college_name IS NULL OR v_college_name = '' THEN
        RAISE EXCEPTION 'College name is required';
    END IF;

    -- Documented Rule: Primary coordinator is the first entry in p_coordinators
    IF jsonb_typeof(p_coordinators) = 'array' AND jsonb_array_length(p_coordinators) > 0 THEN
        v_primary_tpo := nullif(trim(p_coordinators->0->>'name'), '');
    END IF;
    IF v_primary_tpo IS NULL THEN
        v_primary_tpo := nullif(trim(p_college->>'tpo'), '');
    END IF;

    -- 1. Insert College
    INSERT INTO colleges (
        name,
        city,
        course,
        tpo,
        website,
        strength,
        last_contact,
        status,
        institution_type,
        courses_available
    ) VALUES (
        v_college_name,
        nullif(trim(p_college->>'city'), ''),
        nullif(trim(p_college->>'course'), ''),
        v_primary_tpo,
        nullif(trim(p_college->>'website'), ''),
        CASE WHEN (p_college->>'strength') IS NOT NULL AND (p_college->>'strength') ~ '^-?[0-9]+$' THEN (p_college->>'strength')::INTEGER ELSE NULL END,
        CASE WHEN (p_college->>'last_contact') IS NOT NULL AND (p_college->>'last_contact') ~ '^\d{4}-\d{2}-\d{2}$' THEN (p_college->>'last_contact')::DATE ELSE NULL END,
        COALESCE(nullif(trim(p_college->>'status'), ''), 'Interested'),
        nullif(trim(p_college->>'institution_type'), ''),
        nullif(trim(p_college->>'courses_available'), '')
    )
    RETURNING * INTO v_college;

    -- 2. Insert each coordinator and audit history
    IF jsonb_typeof(p_coordinators) = 'array' THEN
        FOR v_coord_item IN SELECT * FROM jsonb_array_elements(p_coordinators)
        LOOP
            v_coord_name := trim(v_coord_item->>'name');
            IF v_coord_name IS NOT NULL AND v_coord_name <> '' THEN
                INSERT INTO placement_coordinators (
                    college_id,
                    name,
                    phone,
                    email,
                    is_current,
                    effective_from,
                    created_at,
                    updated_at,
                    created_by,
                    updated_by,
                    created_by_name,
                    updated_by_name
                ) VALUES (
                    v_college.id,
                    v_coord_name,
                    nullif(trim(v_coord_item->>'phone'), ''),
                    nullif(trim(v_coord_item->>'email'), ''),
                    true,
                    COALESCE((v_coord_item->>'effective_from')::DATE, CURRENT_DATE),
                    now(),
                    now(),
                    v_u.user_id,
                    v_u.user_id,
                    v_u.user_name,
                    v_u.user_name
                )
                RETURNING * INTO v_coord;

                INSERT INTO placement_coordinator_history (
                    college_id,
                    coordinator_id,
                    action,
                    previous_values,
                    new_values,
                    changed_at,
                    changed_by,
                    changed_by_name,
                    changed_by_email
                ) VALUES (
                    v_college.id,
                    v_coord.id,
                    'CREATED',
                    NULL,
                    jsonb_build_object(
                        'name', v_coord.name,
                        'phone', v_coord.phone,
                        'email', v_coord.email,
                        'is_current', true,
                        'effective_from', v_coord.effective_from
                    ),
                    now(),
                    v_u.user_id,
                    v_u.user_name,
                    v_u.user_email
                );

                v_created_coords := v_created_coords || jsonb_build_array(row_to_json(v_coord));
            END IF;
        END LOOP;
    END IF;

    RETURN jsonb_build_object(
        'college', row_to_json(v_college),
        'coordinators', v_created_coords
    );
END;
$$;


