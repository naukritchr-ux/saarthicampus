-- 7B: Update Coordinator Details (atomic update + field diff history + tpo sync if current)
CREATE OR REPLACE FUNCTION update_placement_coordinator_details(
    p_coordinator_id TEXT,
    p_name TEXT,
    p_phone TEXT DEFAULT NULL,
    p_email TEXT DEFAULT NULL,
    p_effective_from DATE DEFAULT NULL
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_u RECORD;
    v_prev RECORD;
    v_updated RECORD;
    v_prev_vals JSONB;
    v_new_vals JSONB;
    v_coord_id_type TEXT;
BEGIN
    -- Strict security: Caller must be authenticated
    SELECT * INTO v_u FROM get_saarthi_auth_user();
    IF v_u.user_id IS NULL AND current_user NOT IN ('postgres', 'service_role', 'supabase_admin') THEN
        RAISE EXCEPTION 'Authentication required: caller must be an authenticated user';
    END IF;

    -- Strict role check: Only admin or recruiter
    IF v_u.user_role NOT IN ('admin', 'recruiter') THEN
        RAISE EXCEPTION 'Unauthorized: only recruiters and admins can manage placement coordinators';
    END IF;

    IF p_name IS NULL OR trim(p_name) = '' THEN
        RAISE EXCEPTION 'Coordinator name is required';
    END IF;

    IF p_coordinator_id IS NULL OR trim(p_coordinator_id) = '' THEN
        RAISE EXCEPTION 'Coordinator ID is required';
    END IF;

    SELECT data_type INTO v_coord_id_type
    FROM information_schema.columns
    WHERE table_name = 'placement_coordinators' AND column_name = 'id';

    IF v_coord_id_type = 'uuid' THEN
        SELECT * INTO v_prev
        FROM placement_coordinators
        WHERE id = p_coordinator_id::UUID;
    ELSE
        SELECT * INTO v_prev
        FROM placement_coordinators
        WHERE id = p_coordinator_id::BIGINT;
    END IF;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Coordinator record not found';
    END IF;

    v_prev_vals := jsonb_build_object(
        'name', v_prev.name,
        'phone', v_prev.phone,
        'email', v_prev.email,
        'effective_from', v_prev.effective_from
    );

    v_new_vals := jsonb_build_object(
        'name', trim(p_name),
        'phone', nullif(trim(p_phone), ''),
        'email', nullif(trim(p_email), ''),
        'effective_from', COALESCE(p_effective_from, v_prev.effective_from)
    );

    -- If identical values, return early
    IF v_prev_vals = v_new_vals THEN
        RETURN to_jsonb(v_prev);
    END IF;

    IF v_coord_id_type = 'uuid' THEN
        UPDATE placement_coordinators
        SET name = trim(p_name),
            phone = nullif(trim(p_phone), ''),
            email = nullif(trim(p_email), ''),
            effective_from = COALESCE(p_effective_from, v_prev.effective_from),
            updated_at = now(),
            updated_by = v_u.user_id,
            updated_by_name = v_u.user_name
        WHERE id = p_coordinator_id::UUID
        RETURNING * INTO v_updated;
    ELSE
        UPDATE placement_coordinators
        SET name = trim(p_name),
            phone = nullif(trim(p_phone), ''),
            email = nullif(trim(p_email), ''),
            effective_from = COALESCE(p_effective_from, v_prev.effective_from),
            updated_at = now(),
            updated_by = v_u.user_id,
            updated_by_name = v_u.user_name
        WHERE id = p_coordinator_id::BIGINT
        RETURNING * INTO v_updated;
    END IF;

    -- Record in audit table
    INSERT INTO placement_coordinator_history (
        college_id,
        coordinator_id,
        action,
        previous_values,
        new_values,
        changed_at,
        changed_by,
        changed_by_name,
        changed_by_email
    ) VALUES (
        v_updated.college_id,
        v_updated.id,
        'UPDATED',
        v_prev_vals,
        v_new_vals,
        now(),
        v_u.user_id,
        v_u.user_name,
        v_u.user_email
    );

    -- Keep colleges.tpo synchronized if this is the current coordinator and name changed
    IF v_updated.is_current AND trim(p_name) IS DISTINCT FROM v_prev.name THEN
        UPDATE colleges
        SET tpo = trim(p_name)
        WHERE id = v_updated.college_id;
    END IF;

    RETURN to_jsonb(v_updated);
END;
$$;


