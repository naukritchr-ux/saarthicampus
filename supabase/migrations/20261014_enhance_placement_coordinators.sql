        WHERE id = p_college_id::UUID;

    ELSE
        SELECT * INTO v_prev
        FROM placement_coordinators
        WHERE college_id = p_college_id::BIGINT AND is_current = true
        LIMIT 1;

        IF FOUND THEN
            UPDATE placement_coordinators
            SET is_current = false,
