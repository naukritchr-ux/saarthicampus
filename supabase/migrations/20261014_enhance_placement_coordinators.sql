-- 7D: Create College With Initial Placement Coordinator (atomic college + coordinator + history + tpo sync)
CREATE OR REPLACE FUNCTION create_college_with_coordinator(
    p_college JSONB,
    p_coord_name TEXT DEFAULT NULL,
    p_coord_phone TEXT DEFAULT NULL,
    p_coord_email TEXT DEFAULT NULL,
    p_coord_effective_from DATE DEFAULT CURRENT_DATE
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
DECLARE
    v_u RECORD;
    v_college RECORD;
    v_coord RECORD;
    v_college_name TEXT;
    v_has_coord BOOLEAN;
BEGIN
    -- Strict security: Caller must be authenticated
    SELECT * INTO v_u FROM get_saarthi_auth_user();
    IF v_u.user_id IS NULL AND current_user NOT IN ('postgres', 'service_role', 'supabase_admin') THEN
        RAISE EXCEPTION 'Authentication required: caller must be an authenticated user';
    END IF;

    -- Strict role check: Only admin or recruiter
    IF v_u.user_role NOT IN ('admin', 'recruiter') THEN
        RAISE EXCEPTION 'Unauthorized: only recruiters and admins can create colleges and placement coordinators';
    END IF;

    v_college_name := trim(p_college->>'name');
    IF v_college_name IS NULL OR v_college_name = '' THEN
        RAISE EXCEPTION 'College name is required';
    END IF;

    v_has_coord := (p_coord_name IS NOT NULL AND trim(p_coord_name) <> '')
                OR (p_coord_phone IS NOT NULL AND trim(p_coord_phone) <> '')
                OR (p_coord_email IS NOT NULL AND trim(p_coord_email) <> '');

    IF v_has_coord AND (p_coord_name IS NULL OR trim(p_coord_name) = '') THEN
        RAISE EXCEPTION 'Coordinator name is required when contact details are provided';
    END IF;

    -- 1. Insert College
    INSERT INTO colleges (
        name,
        city,
        course,
        tpo,
        website,
        strength,
        last_contact,
        status,
        institution_type,
        courses_available
    ) VALUES (
        v_college_name,
        nullif(trim(p_college->>'city'), ''),
        nullif(trim(p_college->>'course'), ''),
        COALESCE(nullif(trim(p_coord_name), ''), nullif(trim(p_college->>'tpo'), '')),
        nullif(trim(p_college->>'website'), ''),
        CASE WHEN (p_college->>'strength') IS NOT NULL AND (p_college->>'strength') ~ '^-?[0-9]+$' THEN (p_college->>'strength')::INTEGER ELSE NULL END,
        CASE WHEN (p_college->>'last_contact') IS NOT NULL AND (p_college->>'last_contact') ~ '^\d{4}-\d{2}-\d{2}$' THEN (p_college->>'last_contact')::DATE ELSE NULL END,
        COALESCE(nullif(trim(p_college->>'status'), ''), 'Interested'),
        nullif(trim(p_college->>'institution_type'), ''),
        nullif(trim(p_college->>'courses_available'), '')
    )
    RETURNING * INTO v_college;

    -- 2. If coordinator details were provided, insert placement_coordinator and history
    IF v_has_coord THEN
        INSERT INTO placement_coordinators (
            college_id,
            name,
            phone,
            email,
            is_current,
            effective_from,
            created_at,
            updated_at,
            created_by,
            updated_by,
            created_by_name,
            updated_by_name
        ) VALUES (
            v_college.id,
            trim(p_coord_name),
            nullif(trim(p_coord_phone), ''),
            nullif(trim(p_coord_email), ''),
            true,
            COALESCE(p_coord_effective_from, CURRENT_DATE),
            now(),
            now(),
            v_u.user_id,
            v_u.user_id,
            v_u.user_name,
            v_u.user_name
        )
        RETURNING * INTO v_coord;

        INSERT INTO placement_coordinator_history (
            college_id,
            coordinator_id,
            action,
            previous_values,
            new_values,
            changed_at,
            changed_by,
            changed_by_name,
            changed_by_email
        ) VALUES (
            v_college.id,
            v_coord.id,
            'CREATED',
            NULL,
            jsonb_build_object(
                'name', v_coord.name,
                'phone', v_coord.phone,
                'email', v_coord.email,
                'is_current', true,
                'effective_from', v_coord.effective_from
            ),
            now(),
            v_u.user_id,
            v_u.user_name,
            v_u.user_email
        );
    END IF;

    RETURN jsonb_build_object(
        'college', row_to_json(v_college),
        'coordinator', CASE WHEN v_has_coord THEN row_to_json(v_coord) ELSE NULL END
    );
END;
$$;


-- 7E: Add Placement Coordinator (adds a new active coordinator without retiring existing active coordinators)
CREATE OR REPLACE FUNCTION add_placement_coordinator(
    p_college_id TEXT,
    p_name TEXT,
    p_phone TEXT DEFAULT NULL,
    p_email TEXT DEFAULT NULL,
    p_effective_from DATE DEFAULT CURRENT_DATE
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
AS $$
