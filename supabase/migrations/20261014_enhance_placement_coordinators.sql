CREATE OR REPLACE FUNCTION get_saarthi_auth_user()
RETURNS TABLE (
    user_id UUID,
    user_name TEXT,
    user_email TEXT,
    user_role TEXT
)
LANGUAGE plpgsql
SECURITY DEFINER
STABLE
AS $$
DECLARE
    v_uid UUID := auth.uid();
    v_name TEXT;
    v_email TEXT;
    v_role TEXT;
BEGIN
    IF v_uid IS NULL THEN
        -- Check if running via Postgres superuser or service role (e.g. backend script)
        IF current_user IN ('postgres', 'service_role', 'supabase_admin') THEN
            RETURN QUERY SELECT NULL::UUID, 'System Admin'::TEXT, 'admin@saarthicampus'::TEXT, 'admin'::TEXT;
        ELSE
            RETURN QUERY SELECT NULL::UUID, NULL::TEXT, NULL::TEXT, NULL::TEXT;
        END IF;
        RETURN;
    END IF;

    -- Lookup from profiles table
    SELECT p.name, p.email, p.role INTO v_name, v_email, v_role
    FROM profiles p
    WHERE p.id = v_uid;

    -- Fallback to JWT metadata if profile row missing or empty
    IF v_name IS NULL OR v_name = '' THEN
        v_name := COALESCE(
            auth.jwt()->'user_metadata'->>'name',
            auth.jwt()->'user_metadata'->>'full_name',
            auth.jwt()->>'email',
            'Authorized User'
        );
    END IF;

    IF v_email IS NULL OR v_email = '' THEN
        v_email := auth.jwt()->>'email';
    END IF;

    IF v_role IS NULL THEN
        v_role := COALESCE(auth.jwt()->'user_metadata'->>'role', 'recruiter');
    END IF;

    RETURN QUERY SELECT v_uid, v_name, v_email, v_role;
END;
$$;

