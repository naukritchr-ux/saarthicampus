        ) VALUES (
            p_college_id::BIGINT,
            trim(p_name),
            nullif(trim(p_phone), ''),
            nullif(trim(p_email), ''),
            true,
            COALESCE(p_effective_from, CURRENT_DATE),
            now(),
            now(),
            v_u.user_id,
            v_u.user_id,
            v_u.user_name,
            v_u.user_name
        )
