-- =====================================================================
-- STEP 3: RESUMES BUCKET POLICIES
-- Buckets: 'resumes', 'Resumes'
-- Public applicants must be able to upload resumes during job application.
-- Only approved staff (admin, recruiter) and approved corporate can view/read.
-- Staff can update/delete.
-- =====================================================================

-- 3A. Public applicant upload
CREATE POLICY "Public student resume upload"
  ON storage.objects
  FOR INSERT
  TO public
  WITH CHECK (bucket_id IN ('resumes', 'Resumes'));

-- 3B. Approved staff & corporate read
CREATE POLICY "Staff and owner read resumes"
  ON storage.objects
  FOR SELECT
  TO authenticated
  USING (
    bucket_id IN ('resumes', 'Resumes') AND (
      EXISTS (
        SELECT 1 FROM profiles
        WHERE profiles.id = auth.uid()
          AND profiles.role IN ('admin', 'recruiter')
          AND profiles.approved = true
      )
      OR
      EXISTS (
        SELECT 1 FROM profiles
        WHERE profiles.id = auth.uid()
          AND profiles.role = 'corporate'
          AND profiles.approved = true
      )
    )
  );

-- 3C. Staff update / delete management
CREATE POLICY "Staff manage resumes"
  ON storage.objects
  FOR ALL
  TO authenticated
  USING (
    bucket_id IN ('resumes', 'Resumes') AND
    EXISTS (
      SELECT 1 FROM profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role IN ('admin', 'recruiter')
        AND profiles.approved = true
    )
  );

-- =====================================================================
-- STEP 4: CANDIDATE PHOTOS BUCKET POLICIES
-- Bucket: 'candidate-photos'
-- Public applicants upload passport photos during registration.
-- Only authenticated, approved platform users can view them.
-- =====================================================================

-- 4A. Public applicant photo upload
CREATE POLICY "Public candidate photo upload"
  ON storage.objects
  FOR INSERT
  TO public
  WITH CHECK (bucket_id = 'candidate-photos');

-- 4B. Authenticated approved read
CREATE POLICY "Authenticated read candidate photos"
  ON storage.objects
  FOR SELECT
  TO authenticated
  USING (
    bucket_id = 'candidate-photos' AND
    EXISTS (
      SELECT 1 FROM profiles
      WHERE profiles.id = auth.uid()
        AND profiles.approved = true
    )
  );

-- =====================================================================
-- STEP 5: CANDIDATE DOCUMENTS BUCKET POLICIES (KYC, marksheets, offer letters)
-- Bucket: 'candidate-documents'
-- High sensitivity: strictly non-public, authenticated approved users only.
-- =====================================================================

-- 5A. Corporate & staff upload
CREATE POLICY "Corporate and staff upload documents"
  ON storage.objects
  FOR INSERT
  TO authenticated
  WITH CHECK (
    bucket_id = 'candidate-documents' AND
    EXISTS (
      SELECT 1 FROM profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role IN ('admin', 'recruiter', 'corporate')
        AND profiles.approved = true
    )
  );

-- 5B. Corporate & staff read
CREATE POLICY "Authorized read candidate documents"
  ON storage.objects
  FOR SELECT
  TO authenticated
  USING (
    bucket_id = 'candidate-documents' AND
    EXISTS (
      SELECT 1 FROM profiles
      WHERE profiles.id = auth.uid()
        AND profiles.role IN ('admin', 'recruiter', 'corporate')
        AND profiles.approved = true
    )
  );
